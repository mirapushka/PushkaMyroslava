//Дано двовимірний масив з N*М цілих чисел. 
// Повернути з функції середнє значення мінімальних елементів кожного з рядків матриці.

#include <iostream> 
#include <cstdlib>  // для функцій rand та srand
#include <ctime>    // для функції time

using namespace std; // стандартний простір імен

// для обчислення середнього мінімальних елементів кожного рядка
double averageOfRowMins(int a[][100], int n, int m) {
    double sum = 0; // сума мінімальних елементів
    for (int i = 0; i < n; i++) { // перебор рядків
        int minVal = a[i][0]; // Вважаємо мінімальним перший елемент поточного рядка
        for (int j = 1; j < m; j++) { // перебор стовпчиків у рядку
            if (a[i][j] < minVal) { // Якщо знайдено елемент менший за поточний мінімальний
                minVal = a[i][j]; // Зберігаємо нове мінімальне значення
            }
        }
        sum += minVal; // Додаємо мінімальний елемент до загальної суми
    }
    return sum / n; // сума поділена на кількість рядків
}

int main() {
    string FNAME = "Пушка"; 
    const int n = 3; //  рядки
    const int m = 4; //  стовпчики
    int a[100][100]; // Оголошення двовимірного масиву

    srand(time(0)); // генератор випадкових чисел

    // Заповнення випадковими числами 
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            a[i][j] = rand() % 20 - 5; 
        }
    }

    cout << "Студент: " << FNAME << endl;
    cout << "Матриця:\n";
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < m; j++) {
            cout << a[i][j] << "\t"; 
        }
        cout << endl; 
    }

    double result = averageOfRowMins(a, n, m);
    
    cout << "Середнє значення мін. елементів кожного рядка: " << result << endl;

    return 0; 
}