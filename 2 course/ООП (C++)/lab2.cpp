// Визначити, у скільки разів виличина цілої частини числа більше за дробову. 
//Організувати перевірку ділення на 0. Результат «обрізати» до другого
//знака після коми. Наприклад,х=123,656 -> y = 656/123 = 0,1875… = 0,18.

#include <iostream> // підключення бібліотеки для введення та виведення даних
#include <cmath>    // підключення бібліотеки для математичних функцій (trunc, round)

using namespace std; // використання стандартного простору імен

int main() { // головна функція програми
    cout << "Студент: Пушка" << endl; 

    double x; // оголошення змінної x 
    cout << "Введіть число x: "; 
    cin >> x; // зчитування введеного числа x з клавіатури

    int a = (int)x; // отримання цілої частини числа шляхом приведення типів
    
    double frac = x - a; // отримання дробової частини числа як 0.XX
    while (frac > 0 && frac - (int)frac > 0.00001) { // цикл для перетворення дробової частини на ціле число
        frac *= 10; // множимо дробову частину на 10 на кожному кроці
    } // кінець циклу while
    int b = (int)round(frac); // збереження дробової частини як цілого числа b

    if (a == 0) { // умовний оператор if для перевірки ділення на нуль
        cout << "Помилка: ціла частина дорівнює 0!" << endl; // виведення повідомлення про помилку
    } // кінець блоку if
    else { // гілка else виконується, якщо ціла частина не дорівнює 0
        double y = (double)b / a; // обчислення частки від ділення b на a

        y = trunc(y * 100) / 100; // обрізання результату y до двох знаків після коми

        cout << "Результат y = " << y << endl; // виведення кінцевого результату y
    } // кінець блоку else

    return 0; // повернення 0 — сигнал про успішне завершення програми
} // кінець функції main