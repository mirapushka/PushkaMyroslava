// Визначити, у скільки разів виличина цілої частини числа більше за дробову. 
//Організувати перевірку ділення на 0. Результат «обрізати» до другого
//знака після коми. Наприклад,х=123,656 -> y = 656/123 = 0,1875… = 0,18.
#include <iostream>
#include <string>
#include <cmath>

using namespace std;

int main() {
    cout << "Студент: Пушка" << endl;

    string s;
    cout << "Введіть число x: ";
    cin >> s; // зчитуємо число як текст, щоб уникнути помилок точності double

    // Шукаємо крапку або кому в числі
    size_t pos = s.find('.');
    if (pos == string::npos) {
        pos = s.find(',');
    }

    int a = 0; // ціла частина
    int b = 0; // дробова частина як ціле число

    if (pos != string::npos) {
        a = stoi(s.substr(0, pos));          // беремо все до коми
        string fracStr = s.substr(pos + 1);  // беремо все після коми
        if (!fracStr.empty()) {
            b = stoi(fracStr);
        }
    } else {
        a = stoi(s); // якщо дробової частини немає взагалі
    }

    // Перевірка ділення на 0 (залежно від того, що в знаменнику)
    if (b == 0) {
        cout << "Помилка: дробова частина дорівнює 0, ділення неможливе!" << endl;
    } else {
        // Рахуємо, у скільки разів ціла частина (a) більша за дробову (b)
        // Для 123.656: 123 / 656 = 0.1875 -> обрізаємо до 0.18
        double y = (double)a / b; 
        y = trunc(y * 100) / 100;

        cout << "Результат y = " << y << endl;
    }

    return 0;
}